/* =====================================================================
 * 技能书 / 专家智能体系统（阶段三）
 * ---------------------------------------------------------------------
 * 为不同学科、题型分别维护"专家答题说明书"：
 *   - 每本技能书 = 一位专家智能体（角色定位 + 工作流程 + 必覆盖要点 + 易错规避）
 *   - routeSkill() 根据问题内容打分、路由到最匹配的专家
 *   - buildSkillGuidance() 生成注入给最终作答模型的专家方法论
 * 新增学科只需在 SKILL_BOOKS 注册，不必改路由逻辑。
 * ===================================================================== */

export interface SkillBook {
  id: string;
  name: string;                  // 专家/技能书名称（前端可展示）
  agentRole: string;             // 智能体身份与语气
  strongKeywords: string[];      // 强特征词（命中 +2，几乎确定分科）
  weakKeywords: string[];        // 弱特征词（命中 +1，多学科共有）
  patterns?: RegExp[];           // 正则特征（命中 +3）
  methodology: string;           // 专家答题工作流程（注入提示）
  pitfalls: string;              // 本学科常见错误规避（注入提示）
}

