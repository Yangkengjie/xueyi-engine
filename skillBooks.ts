/* ---------------- 路由 ---------------- */

/* 计算某技能书对问题的匹配分 */
function scoreFor(skill: SkillBook, q: string): number {
  let score = 0;
  for (const kw of skill.strongKeywords) {
    if (kw && q.includes(kw)) score += 2;
  }
  for (const kw of skill.weakKeywords) {
    if (kw && q.includes(kw)) score += 1;
  }
  if (skill.patterns) {
    for (const re of skill.patterns) {
      if (re.test(q)) score += 3;
    }
  }
  return score;
}

/* 路由到最匹配的专家；都低于阈值则用通用学伴 */
export function routeSkill(question: string): SkillBook {
  const q = String(question || '');
  let best: SkillBook = GENERAL;
  let bestScore = 0;
  for (const skill of SKILL_BOOKS) {
    const s = scoreFor(skill, q);
    if (s > bestScore) { bestScore = s; best = skill; }
  }
  return bestScore >= 2 ? best : GENERAL;
}

/* 注入给最终作答模型的专家方法论 + 给前端的元信息 */
export interface SkillGuidance {
  skillId: string;
  skillName: string;
  agentRole: string;
  guidance: string;
}

export function buildSkillGuidance(question: string): SkillGuidance {
  const skill = routeSkill(question);
  const guidance = `【当前以「${skill.name}」身份作答】
${skill.agentRole}
${skill.methodology}
${skill.pitfalls}`;
  return {
    skillId: skill.id,
    skillName: skill.name,
    agentRole: skill.agentRole,
    guidance,
  };
}

/* 前端可用的技能书清单（名称/ID） */
export function listSkills() {
  return SKILL_BOOKS.map((s) => ({ id: s.id, name: s.name }));
}
